/** لون المجموعة، يدور على شخصيات المراحل حتى لا تتشابه البطاقات */
export const GROUP_TONE = ['s1', 's2', 's3', 's4', 's5', 's6', 's7'] as const;

export function toneFor(i: number): string {
  return GROUP_TONE[i % GROUP_TONE.length] as string;
}
